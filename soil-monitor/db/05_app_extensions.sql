-- 05_app_extensions.sql
-- Доповнення до стартової схеми (01–03) для повноцінної web-системи.
-- Закриває «Зауваження 5» з Додатку В: users, method_sources, атрибути ділянки.
-- Таблиці 01_schema.sql НЕ змінюються за змістом — лише додаються нові таблиці та колонки.
BEGIN;

-- 1. Користувачі (табл. 3.3). Ролі: admin — довідники й база знань;
--    specialist — точки, вимірювання, оцінювання; viewer — лише перегляд.
CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  full_name TEXT,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','specialist','viewer')) DEFAULT 'specialist',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Джерела методів (табл. 3.3, method_sources). Стартове наповнення — з source_url.
CREATE TABLE IF NOT EXISTS method_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  method_id BIGINT NOT NULL REFERENCES remediation_methods(id) ON DELETE CASCADE,
  source_title TEXT NOT NULL,
  source_url TEXT NOT NULL,
  UNIQUE (method_id, source_url)
);
INSERT INTO method_sources (method_id, source_title, source_url)
SELECT id, 'FRTR Remediation Technologies Screening Matrix', source_url FROM remediation_methods
ON CONFLICT (method_id, source_url) DO NOTHING;

-- 3. Характеристики ділянки для скринінгу методів (ключі method_criteria).
--    NULL = «невідомо» → needs_data. Значення НЕ виводяться автоматично з бала R.
CREATE TABLE IF NOT EXISTS site_characteristics (
  location_id BIGINT PRIMARY KEY REFERENCES monitoring_locations(id) ON DELETE CASCADE,
  contamination_confirmed BOOLEAN,
  measurement_uncertain BOOLEAN,
  plant_growth_suitable BOOLEAN,
  bioavailability_assessed BOOLEAN,
  soil_properties_known BOOLEAN,
  amendment_tested BOOLEAN,
  grain_size_known BOOLEAN,
  washing_feasibility_tested BOOLEAN,
  localized_extent_confirmed BOOLEAN,
  disposal_route_known BOOLEAN,
  exposure_pathway_present BOOLEAN,
  notes TEXT,
  updated_by BIGINT REFERENCES users(id),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO site_characteristics (location_id)
SELECT id FROM monitoring_locations ON CONFLICT DO NOTHING;

-- 4. Додаткові поля точки
ALTER TABLE monitoring_locations ADD COLUMN IF NOT EXISTS district TEXT;
ALTER TABLE monitoring_locations ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
-- sampling_site — точка відбору; settlement — координати населеного пункту (поле не локалізоване);
-- district_average — середнє по природно-сільськогосподарському району (маркер у його умовному центрі)
ALTER TABLE monitoring_locations ADD COLUMN IF NOT EXISTS location_type TEXT NOT NULL DEFAULT 'sampling_site'
  CHECK (location_type IN ('sampling_site','settlement','district_average'));
ALTER TABLE monitoring_locations ADD COLUMN IF NOT EXISTS area_thousand_ha NUMERIC(9,1);

-- 5. Відтворюваність оцінювання (вимога 3.1): входи, деталі виведення, автор
ALTER TABLE soil_measurements ADD COLUMN IF NOT EXISTS sample_depth_cm TEXT;
ALTER TABLE soil_measurements ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES users(id);
ALTER TABLE soil_measurements ADD COLUMN IF NOT EXISTS source_url TEXT;
ALTER TABLE soil_measurements ADD COLUMN IF NOT EXISTS period_label TEXT;      -- напр. «середнє 2001–2020»
ALTER TABLE soil_measurements ADD COLUMN IF NOT EXISTS ap_details JSONB;       -- 5 експертних критеріїв × 0..2
ALTER TABLE soil_measurements ADD COLUMN IF NOT EXISTS notes TEXT;

-- Значення поза математичною областю FIS (напр. Pb > 30 мг/кг) зберігаються окремо,
-- а не зводяться до верхньої межі (вимога README моделі А).
CREATE TABLE IF NOT EXISTS measurement_exceptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id BIGINT NOT NULL REFERENCES monitoring_locations(id) ON DELETE CASCADE,
  sample_date DATE NOT NULL,
  indicator TEXT NOT NULL CHECK (indicator IN ('pb','cd','zn','ph','ap')),
  value NUMERIC(12,4) NOT NULL,
  reason TEXT NOT NULL,
  provenance TEXT NOT NULL,
  source_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE fuzzy_assessments ADD COLUMN IF NOT EXISTS input_snapshot JSONB;
ALTER TABLE fuzzy_assessments ADD COLUMN IF NOT EXISTS result_details JSONB;
ALTER TABLE fuzzy_assessments ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES users(id);
CREATE INDEX IF NOT EXISTS idx_assessments_measurement ON fuzzy_assessments(measurement_id, created_at DESC);

-- 6. Аудит запусків AI-відбору
ALTER TABLE strategy_sets ADD COLUMN IF NOT EXISTS llm_model TEXT;
ALTER TABLE strategy_sets ADD COLUMN IF NOT EXISTS situation_profile JSONB;
ALTER TABLE strategy_sets ADD COLUMN IF NOT EXISTS screening JSONB;
ALTER TABLE strategy_sets ADD COLUMN IF NOT EXISTS error_message TEXT;
ALTER TABLE strategy_sets ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES users(id);
CREATE INDEX IF NOT EXISTS idx_strategy_sets_assessment ON strategy_sets(assessment_id, created_at DESC);

-- Синхронізувати лічильники identity після явних ID у seed (9001, 9002 …)
COMMIT;
