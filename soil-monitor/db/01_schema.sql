BEGIN;
CREATE TABLE IF NOT EXISTS monitoring_locations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, latitude NUMERIC(9,6) NOT NULL CHECK(latitude BETWEEN -90 AND 90),
 longitude NUMERIC(9,6) NOT NULL CHECK(longitude BETWEEN -180 AND 180),
 land_use TEXT, source_status TEXT CHECK(source_status IN ('none','suspected','confirmed','unknown')) DEFAULT 'unknown',
 description TEXT, is_demo BOOLEAN NOT NULL DEFAULT FALSE);
CREATE TABLE IF NOT EXISTS soil_measurements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 location_id BIGINT NOT NULL REFERENCES monitoring_locations(id), sample_date DATE NOT NULL,
 pb NUMERIC(9,4) CHECK(pb BETWEEN 0 AND 30), cd NUMERIC(9,4) CHECK(cd BETWEEN 0 AND 3.5),
 zn NUMERIC(9,4) CHECK(zn BETWEEN 0 AND 115), ph NUMERIC(5,2) CHECK(ph BETWEEN 3 AND 10),
 ap SMALLINT CHECK(ap BETWEEN 0 AND 10),
 ph_method TEXT, metal_extraction_method TEXT, provenance TEXT NOT NULL, is_demo BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
CREATE TABLE IF NOT EXISTS fuzzy_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 measurement_id BIGINT NOT NULL REFERENCES soil_measurements(id), score NUMERIC(7,4) NOT NULL CHECK(score BETWEEN 0 AND 10),
 category TEXT NOT NULL CHECK(category IN ('low','moderate','high','critical')),
 model_version TEXT NOT NULL, is_demo BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
CREATE TABLE IF NOT EXISTS remediation_methods (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
 category TEXT NOT NULL CHECK(category IN ('monitoring','prevention','remediation')),
 target_pollutants TEXT[] NOT NULL DEFAULT ARRAY['Pb','Cd','Zn'],
 purpose TEXT NOT NULL, application_conditions TEXT NOT NULL,
 advantages TEXT NOT NULL, limitations TEXT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, version INTEGER NOT NULL DEFAULT 1,
 source_url TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS method_criteria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 method_id BIGINT NOT NULL REFERENCES remediation_methods(id) ON DELETE CASCADE,
 condition_key TEXT NOT NULL, operator TEXT NOT NULL CHECK(operator IN ('equals','in')),
 expected_value TEXT NOT NULL, is_required BOOLEAN NOT NULL,
 explanation TEXT NOT NULL,
 UNIQUE(method_id,condition_key));
CREATE TABLE IF NOT EXISTS strategy_sets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assessment_id BIGINT NOT NULL REFERENCES fuzzy_assessments(id),
 status TEXT NOT NULL CHECK(status IN ('demo','generated','validated','failed')),
 selection_engine TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 is_demo BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT demo_consistency CHECK ((status='demo' AND is_demo) OR status<>'demo'));
CREATE TABLE IF NOT EXISTS strategy_alternatives (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 strategy_set_id BIGINT NOT NULL REFERENCES strategy_sets(id) ON DELETE CASCADE,
 method_id BIGINT NOT NULL REFERENCES remediation_methods(id),
 rank SMALLINT NOT NULL CHECK(rank BETWEEN 1 AND 9),
 suitability_status TEXT NOT NULL CHECK(suitability_status IN ('potentially_suitable','needs_data')),
 explanation TEXT NOT NULL, missing_data TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
 is_demo BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE(strategy_set_id,method_id), UNIQUE(strategy_set_id,rank));
CREATE INDEX IF NOT EXISTS idx_measurements_location_date ON soil_measurements(location_id,sample_date DESC);
CREATE INDEX IF NOT EXISTS idx_method_criteria_method ON method_criteria(method_id);
CREATE INDEX IF NOT EXISTS idx_strategy_alternatives_set ON strategy_alternatives(strategy_set_id);
COMMIT;
